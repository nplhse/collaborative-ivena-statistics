<?php

declare(strict_types=1);

namespace App\Shared\Infrastructure\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

final class AppConfiguration implements ConfigurationInterface
{
    #[\Override]
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('app');

        $rootNode = $treeBuilder->getRootNode();

        $rootNode
            ->children()
                ->scalarNode('title')
                    ->isRequired()
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('short_title')
                    ->isRequired()
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('default_locale')
                    ->isRequired()
                    ->cannotBeEmpty()
                ->end()
                ->arrayNode('blog')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('title')
                            ->defaultValue('Blog')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('description')
                            ->defaultValue('Neuigkeiten, Updates und Hintergrundinformationen.')
                            ->cannotBeEmpty()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('content')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('default_locale')
                            ->defaultValue('en')
                            ->cannotBeEmpty()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('meta')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('copyright_start_year')
                            ->defaultValue(2025)
                            ->min(2000)
                        ->end()
                        ->arrayNode('hoster')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->scalarNode('name')
                                    ->defaultValue('')
                                ->end()
                                ->scalarNode('url')
                                    ->defaultValue('')
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('import')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('reject_writer')
                            ->values(['csv', 'db'])
                            ->defaultValue('csv')
                        ->end()
                        ->scalarNode('csv_reject_dir')
                            ->defaultValue('var/import_rejects')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('registration')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('blocked_email_domains')
                            ->scalarPrototype()->end()
                            ->defaultValue(['.ru'])
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('closure_volume')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('reference_weeks_before')
                            ->info('Weeks before the event start that feed the reference (ADR 015).')
                            ->defaultValue(4)
                            ->min(0)
                        ->end()
                        ->integerNode('reference_weeks_after')
                            ->info('Weeks after the event end that feed the reference (ADR 015).')
                            ->defaultValue(4)
                            ->min(0)
                        ->end()
                        ->integerNode('minimum_reference_slots')
                            ->defaultValue(4)
                            ->min(1)
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('job_runs')
                    ->info('Thresholds and expected interval per background job (job_run.job). A missing value is not checked (ADR 018, ADR 019).')
                    ->useAttributeAsKey('job')
                    ->arrayPrototype()
                        ->children()
                            ->integerNode('slow_seconds')->defaultNull()->min(1)->end()
                            ->integerNode('long_seconds')->defaultNull()->min(1)->end()
                            ->integerNode('memory_mb')->defaultNull()->min(1)->end()
                            ->integerNode('overdue_after_minutes')
                                ->info('A scheduler job without a finished run for this long is overdue (ADR 019); null for jobs that are not scheduled.')
                                ->defaultNull()
                                ->min(1)
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('job_runs_retention')
                    ->info('Days job_run rows are kept (ADR 019): routine runs (succeeded or skipped, no exceeded threshold), every other run.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('routine_days')->defaultValue(180)->min(1)->end()
                        ->integerNode('other_days')->defaultValue(730)->min(1)->end()
                    ->end()
                ->end()
                ->arrayNode('messenger_monitoring')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('health')
                            ->info('Limits of the Messenger health checks (ADR 019).')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('backlog_warning_minutes')->info('Oldest ready message older than this: degraded.')->defaultValue(30)->min(1)->end()
                                ->integerNode('backlog_critical_minutes')->info('Oldest ready message older than this: unhealthy.')->defaultValue(120)->min(1)->end()
                                ->integerNode('stalled_after_minutes')->info('Ready messages this old without any handling attempt for as long: unhealthy.')->defaultValue(15)->min(1)->end()
                                ->integerNode('retry_rate_warning_percent')->info('Retry rate of the last 24 hours above this: degraded.')->defaultValue(10)->min(1)->max(100)->end()
                                ->integerNode('retry_min_attempts')->info('The retry rate is only judged with at least this many attempts in 24 hours.')->defaultValue(20)->min(1)->end()
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (array $health): bool => $health['backlog_warning_minutes'] >= $health['backlog_critical_minutes'])
                                ->thenInvalid('backlog_warning_minutes must be lower than backlog_critical_minutes. Got %s.')
                            ->end()
                        ->end()
                        ->arrayNode('retention')
                            ->info('Days Messenger monitoring data is kept (ADR 019); hourly counters are then folded into daily rows.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('hourly_days')->defaultValue(90)->min(31)->end()
                                ->integerNode('failure_days')->defaultValue(30)->min(1)->end()
                                ->integerNode('queue_sample_days')->defaultValue(90)->min(31)->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('storage')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('thresholds')
                            ->info('Usage in percent of the capacity reference at which a level starts (ADR 017); exceeded is always 100.')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('notice_percent')->defaultValue(80)->min(1)->max(99)->end()
                                ->integerNode('warning_percent')->defaultValue(90)->min(1)->max(99)->end()
                                ->integerNode('critical_percent')->defaultValue(99)->min(1)->max(99)->end()
                            ->end()
                            ->validate()
                                ->ifTrue(static fn (array $thresholds): bool => $thresholds['notice_percent'] >= $thresholds['warning_percent'] || $thresholds['warning_percent'] >= $thresholds['critical_percent'])
                                ->thenInvalid('Storage thresholds must increase strictly: notice < warning < critical (< 100). Got %s.')
                            ->end()
                        ->end()
                        ->integerNode('measurement_max_age_hours')
                            ->info('A measurement older than this is stale for Application Health.')
                            ->defaultValue(36)
                            ->min(1)
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('feedback')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('spam')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('min_submission_seconds')
                                    ->defaultValue(4)
                                    ->min(1)
                                ->end()
                                ->integerNode('long_message_threshold')
                                    ->defaultValue(1800)
                                    ->min(200)
                                ->end()
                                ->integerNode('max_message_length')
                                    ->defaultValue(4000)
                                    ->min(200)
                                ->end()
                                ->integerNode('anonymous_threshold')
                                    ->defaultValue(6)
                                    ->min(1)
                                ->end()
                                ->integerNode('authenticated_threshold')
                                    ->defaultValue(8)
                                    ->min(1)
                                ->end()
                                ->integerNode('authenticated_score_bonus')
                                    ->defaultValue(2)
                                    ->min(0)
                                ->end()
                                ->arrayNode('keywords')
                                    ->scalarPrototype()->end()
                                    ->defaultValue([
                                        'casino',
                                        'crypto',
                                        'loan',
                                        'viagra',
                                        'seo',
                                        'backlink',
                                        'guest post',
                                        'cialis',
                                        'forex',
                                        'nft',
                                        'weight loss',
                                        'make money',
                                        'click here',
                                    ])
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
