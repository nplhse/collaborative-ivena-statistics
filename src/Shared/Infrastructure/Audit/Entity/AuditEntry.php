<?php

declare(strict_types=1);

namespace App\Shared\Infrastructure\Audit\Entity;

use App\Shared\Infrastructure\Audit\Repository\AuditEntryRepository;
use App\User\Domain\Entity\User;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

/**
 * EasyAdmin / Doctrine metadata use these getters; not all appear as direct calls in static analysis.
 *
 * @psalm-suppress ClassMustBeFinal
 */
#[ORM\Entity(repositoryClass: AuditEntryRepository::class)]
#[ORM\Table(name: 'audit_log')]
#[ORM\Index(name: 'idx_audit_log_request', columns: ['request_id'])]
#[ORM\Index(name: 'idx_audit_log_entity', columns: ['entity_class', 'entity_id'])]
#[ORM\Index(name: 'idx_audit_log_time', columns: ['occurred_at', 'id'])]
#[ORM\Index(name: 'idx_audit_log_actor', columns: ['actor_id'])]
#[ORM\Index(name: 'idx_audit_log_actor_time', columns: ['actor_id', 'occurred_at', 'id'])]
#[ORM\Index(name: 'idx_audit_log_intent', columns: ['intent'])]
#[ORM\Index(name: 'idx_audit_log_session', columns: ['session_ref'])]
class AuditEntry
{
    /** Request id generated by the application (ADR 025). */
    public const string REQUEST_ID_GENERATED = 'generated';

    /** Request id written before ADR 025; it may have come from a client header. */
    public const string REQUEST_ID_LEGACY = 'legacy';

    public const string OUTCOME_SUCCESS = 'success';

    public const string OUTCOME_BLOCKED = 'blocked';

    public const string OUTCOME_FAILED = 'failed';

    public const string INTENT_IMPORT_RUN_FAILED = 'import.run.failed';

    public const string ACTION_EXPORT = 'export';

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    /** Copy of metadata.intent, for filtering. */
    #[ORM\Column(length: 128, nullable: true)]
    private ?string $intent;

    /** Outcome where the entry records one (exports, failed import runs), otherwise null. */
    #[ORM\Column(length: 16, nullable: true)]
    private ?string $outcome;

    /** Rows written without a value (all rows from before ADR 025) are legacy. */
    #[ORM\Column(length: 16, options: ['default' => self::REQUEST_ID_LEGACY])]
    private string $requestIdKind = self::REQUEST_ID_GENERATED;

    /**
     * @param array<string, mixed>      $changes
     * @param array<string, mixed>|null $metadata
     */
    public function __construct(
        #[ORM\Column(type: Types::DATETIME_IMMUTABLE)]
        private \DateTimeImmutable $occurredAt,
        #[ORM\Column(length: 128)]
        private string $requestId,
        #[ORM\ManyToOne(targetEntity: User::class)]
        #[ORM\JoinColumn(nullable: true, onDelete: 'SET NULL')]
        private ?User $actor,
        #[ORM\Column(length: 32)]
        private string $origin,
        #[ORM\Column(length: 16)]
        private string $action,
        #[ORM\Column(length: 255)]
        private string $entityClass,
        #[ORM\Column(length: 64, nullable: true)]
        private ?string $entityId,
        #[ORM\Column(type: Types::JSON)]
        private array $changes,
        #[ORM\Column(type: Types::JSON, nullable: true)]
        private ?array $metadata,
        #[ORM\Column(type: Types::GUID, nullable: true)]
        private ?string $sessionRef = null,
    ) {
        $this->intent = self::intentFrom($metadata);
        $this->outcome = self::outcomeFrom($action, $metadata);
    }

    /**
     * The backfill (`AuditDerivedColumnsBackfillQuery`) applies the same rule in SQL.
     *
     * @param array<string, mixed>|null $metadata
     */
    public static function intentFrom(?array $metadata): ?string
    {
        $intent = $metadata['intent'] ?? null;

        return \is_string($intent) && '' !== $intent ? $intent : null;
    }

    /**
     * Only outcomes the entry itself states; nothing is inferred. The backfill applies the same rule in SQL.
     *
     * @param array<string, mixed>|null $metadata
     */
    public static function outcomeFrom(string $action, ?array $metadata): ?string
    {
        if (self::ACTION_EXPORT === $action && null !== $metadata) {
            if (true === ($metadata['blocked'] ?? null)) {
                return self::OUTCOME_BLOCKED;
            }

            return match ($metadata['success'] ?? null) {
                true => self::OUTCOME_SUCCESS,
                false => self::OUTCOME_FAILED,
                default => null,
            };
        }

        return self::INTENT_IMPORT_RUN_FAILED === self::intentFrom($metadata) ? self::OUTCOME_FAILED : null;
    }

    /** @psalm-suppress PossiblyUnusedMethod */
    public function getId(): ?int
    {
        return $this->id;
    }

    public function setEntityId(?string $entityId): void
    {
        $this->entityId = $entityId;
    }

    /** @psalm-suppress PossiblyUnusedMethod */
    public function getOccurredAt(): \DateTimeImmutable
    {
        return $this->occurredAt;
    }

    public function getRequestId(): string
    {
        return $this->requestId;
    }

    /** @psalm-suppress PossiblyUnusedMethod */
    public function getActor(): ?User
    {
        return $this->actor;
    }

    /** @psalm-suppress PossiblyUnusedMethod */
    public function getOrigin(): string
    {
        return $this->origin;
    }

    /** @psalm-suppress PossiblyUnusedMethod */
    public function getAction(): string
    {
        return $this->action;
    }

    public function getEntityClass(): string
    {
        return $this->entityClass;
    }

    public function getEntityId(): ?string
    {
        return $this->entityId;
    }

    /**
     * @return array<string, mixed>
     */
    public function getChanges(): array
    {
        return $this->changes;
    }

    /**
     * @return array<string, mixed>|null
     */
    public function getMetadata(): ?array
    {
        return $this->metadata;
    }
}
